#!/usr/bin/env python3
"""Maintainer-only image builder; normal CLI preparation is implemented in Go."""
import argparse
import base64
import concurrent.futures
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import re
import shutil
import tarfile

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("fc_inputs", HERE / "inputs.py")
inputs = importlib.util.module_from_spec(spec)
spec.loader.exec_module(inputs)


# Mirrors internal/firecracker/truststore_linux.go: the pinned ca-certificates
# package replaces the base Mozilla set, and the store is regenerated as a fresh
# installation would leave it, without running package scripts.
CA_DIR = "usr/share/ca-certificates"
MOZILLA_CERTS = CA_DIR + "/mozilla"
LOCAL_CERTS = "usr/local/share/ca-certificates"
ETC_CERTS = "etc/ssl/certs"
CERTS_BUNDLE = ETC_CERTS + "/ca-certificates.crt"
CERTS_CONF = "etc/ca-certificates.conf"
CERTS_CONF_HEADER = """# This file lists certificates that you wish to use or to ignore to be
# installed in /etc/ssl/certs.
# update-ca-certificates(8) will update /etc/ssl/certs by reading this file.
#
# This is autogenerated by dpkg-reconfigure ca-certificates.
# Certificates should be installed under /usr/share/ca-certificates
# and files with extension '.crt' is recognized as available certs.
#
# line begins with # is comment.
# line begins with ! is certificate filename to be deselected.
#
"""
DISTRUSTED_ROOTS = {
    "86a1ecba089c4a8d3bbe2734c612ba341d813e043cf9e8a862cd5c57a36bbe6b": "emSign ECC Root CA - G3",
    "d7a7a0fb5d7e2731d771e9484ebcdef71d5f0c3e0a2948782bc83ee0ea699ef4": "AAA Certificate Services",
}
HASH_LINK = re.compile(r"[0-9a-f]{8}\.r?[0-9]+")


def build(args):
    inputs.require_platform()
    inputs.require_tools(["mkfs.ext4", "debugfs", "dpkg-deb", "readelf", "openssl", args.unsquashfs])
    out = inputs.new_directory(args.output)
    source = out / "inputs"
    source.mkdir()
    inputs.PINS.update(json.loads((HERE / "runtime-pins.json").read_text()))
    names = set(inputs.PINS) - inputs.KERNEL_INPUTS
    cache = Path(args.cache).resolve() if args.cache else None
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        list(pool.map(lambda name: inputs.download(name, source, cache), sorted(names)))
    kernel = Path(args.kernel_build).resolve()
    manifest = json.loads((kernel / "kernel.json").read_text())
    if (manifest.get("inputs") != {name: inputs.PINS[name] for name in sorted(inputs.KERNEL_INPUTS)}
            or manifest.get("enabled") != inputs.KERNEL_EXTRAS
            or manifest.get("disabled") != inputs.KERNEL_DISABLED
            or manifest.get("kernel_sha256") != inputs.digest(kernel / "kernel")
            or manifest.get("config_sha256") != inputs.digest(kernel / "kernel.config")):
        raise RuntimeError("kernel recipe or artifacts differ from the verified pinned build")
    config = (kernel / "kernel.config").read_text().splitlines()
    for name in ["SECURITY_LANDLOCK", "OVERLAY_FS", "FUSE_FS", "TUN", "VIRTIO_VSOCKETS", "SECCOMP_FILTER", "NET_NS", "VETH", "NF_TABLES", "CGROUPS"]:
        if f"CONFIG_{name}=y" not in config:
            raise RuntimeError(f"kernel lacks {name}")
    if not any(line.startswith('CONFIG_LSM="') and "landlock" in line for line in config):
        raise RuntimeError("Landlock is not enabled in the LSM list")
    stage = out / "rootfs-tree"
    with (out / "extract.log").open("x") as log:
        inputs.run([args.unsquashfs, "-no-xattrs", "-no-progress", "-processors", "2", "-excludes", "-dest", stage, source / "ubuntu.squashfs", "dev"], stdout=log, stderr=log)
    # Remove fixture identities, generated machine credentials and boot services.
    for name in ["root/.ssh", "etc/ssh", "var/lib/cloud", "etc/machine-id"]:
        path = stage / name
        if path.is_symlink() or path.is_file():
            path.unlink()
        elif path.is_dir():
            shutil.rmtree(path)
    for name in ["dev", "proc", "sys", "run", "tmp", "mnt", "var", "opt/yoloctl", "etc/yoloctl", "etc/openshell-tls", "etc/ssh", "etc/sudoers.d", "etc/containerd", "etc/cni/net.d", "opt/cni/bin", "usr/local/bin", "home/yolo"]:
        (stage / name).mkdir(parents=True, exist_ok=True)
    drop_legacy_openshell(stage)
    drop_managed_certificates(stage)
    for name in sorted(names):
        if name.endswith(".deb"):
            inputs.run(["dpkg-deb", "-x", source / name, stage])
    # dpkg-deb can replace usr-merge links with package directories (notably
    # fuse3's /bin). Merge those entries before restoring the canonical links.
    for name in ["bin", "sbin", "lib", "lib64"]:
        path = stage / name
        if path.is_dir() and not path.is_symlink():
            target = stage / "usr" / name
            target.mkdir(parents=True, exist_ok=True)
            shutil.copytree(path, target, symlinks=True, dirs_exist_ok=True)
            shutil.rmtree(path)
            path.symlink_to("usr/" + name)
    rebuild_trust_store(stage)
    # dpkg extraction does not run update-alternatives. Select nft explicitly;
    # these are image-local links and never alter host alternatives.
    for family in ["iptables", "ip6tables", "arptables", "ebtables"]:
        for suffix in ["", "-save", "-restore"]:
            link = stage / "usr/sbin" / (family + suffix)
            link.unlink(missing_ok=True)
            link.symlink_to(family + "-nft" + suffix)
    with tarfile.open(source / "nerdctl.tgz", "r:gz") as archive:
        members = [member.name for member in archive.getmembers() if member.isfile() and (member.name.startswith("bin/") or member.name.startswith("libexec/cni/"))]
    for name in members:
        dest = stage / ("opt/cni/bin" if name.startswith("libexec/cni/") else "usr/local/bin") / Path(name).name
        inputs.tar_file(source / "nerdctl.tgz", name, dest)
    (stage / "etc/containerd/config.toml").write_text('version = 2\nroot = "/var/lib/containerd"\nstate = "/run/containerd"\ndisabled_plugins = ["io.containerd.grpc.v1.cri", "io.containerd.cri.v1.runtime", "io.containerd.cri.v1.images"]\n')
    (stage / "etc/ssh/sshd_microvm_config").write_text('''Port 2222
ListenAddress 127.0.0.1
HostKey /run/ssh/host_ed25519
AuthorizedKeysFile /run/ssh/authorized_keys
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitRootLogin no
AllowUsers yolo
UsePAM no
StrictModes yes
PidFile /run/ssh/sshd.pid
Subsystem sftp internal-sftp
''')
    # sudo's setuid bit is preserved in the ext4 inode; the unprivileged host
    # cannot obtain privileges by invoking this private staging-tree binary.
    (stage / "usr/bin/sudo").chmod(0o4755)
    init = Path(args.init_binary)
    if inputs.digest(init) != args.init_sha256:
        raise RuntimeError("guest init changed during preparation")
    shutil.copyfile(init, stage / "sbin/yoloctl-init")
    (stage / "sbin/yoloctl-init").chmod(0o755)
    verify_runtime(stage)
    rootfs = out / "rootfs.ext4"
    with rootfs.open("xb") as stream:
        stream.truncate(2 * 1024**3)
    with (out / "filesystem.log").open("x") as log:
        inputs.run(["mkfs.ext4", "-q", "-F", "-O", "^orphan_file", "-E", "lazy_itable_init=0,lazy_journal_init=0,root_owner=0:0", "-d", stage, rootfs], stdout=log, stderr=log)
        commands = out / "root-ownership.debugfs"
        with commands.open("x") as stream:
            for parent, dirs, files in os.walk(stage, followlinks=False):
                for name in dirs + files:
                    rel = "/" + str((Path(parent) / name).relative_to(stage))
                    if any(c in rel for c in '\n\r"'):
                        raise RuntimeError("unsupported image pathname")
                    stream.write(f'set_inode_field "{rel}" uid 0\nset_inode_field "{rel}" gid 0\n')
        inputs.run(["debugfs", "-w", "-f", commands, rootfs], stdout=log, stderr=log)
    for name in ["/etc", "/opt/yoloctl", "/sbin/yoloctl-init", "/usr/bin/sudo"]:
        result = inputs.run(["debugfs", "-R", f"stat {name}", rootfs], capture_output=True, text=True)
        if not re.search(r"User:\s+0\s+Group:\s+0\b", result.stdout):
            raise RuntimeError(f"guest ownership verification failed: {name}")
    shutil.copyfile(kernel / "kernel", out / "kernel")
    inputs.tar_file(source / "firecracker.tgz", "release-v1.17.0-x86_64/firecracker-v1.17.0-x86_64", out / "firecracker")
    for path in [rootfs, out / "kernel"]:
        path.chmod(0o444)
    inputs.save_json(out / "image.json", {"schema": 1, "architecture": "amd64", "guest_protocol": args.guest_protocol, "kernel_sha256": inputs.digest(out / "kernel"), "rootfs_sha256": inputs.digest(rootfs), "firecracker_sha256": inputs.digest(out / "firecracker")})
    inputs.save_json(out / "provenance.json", {"inputs": inputs.PINS, "kernel": json.loads((kernel / "kernel.json").read_text()), "guest_sha256": inputs.digest(stage / "sbin/yoloctl-init")})
    print(f"Prepared microVM image: {out}")


def guest_path(stage, path):
    """Resolve guest links inside the staging tree, never against host /lib."""
    parts = list(Path(path.lstrip("/")).parts)
    current = stage
    links = 0
    while parts:
        part = parts.pop(0)
        if part == "..":
            if current == stage:
                raise RuntimeError("guest path escapes image")
            current = current.parent
            continue
        current = current / part
        if current.is_symlink():
            links += 1
            if links > 40:
                raise RuntimeError("guest symlink loop")
            target = os.readlink(current)
            current = stage if target.startswith("/") else current.parent
            parts = list(Path(target.lstrip("/")).parts) + parts
    return current


def staged_directory(stage, rel):
    """Return a staging directory that no guest or host link redirects."""
    path = stage / rel
    if path.is_symlink() or not path.is_dir() or guest_path(stage, "/" + rel) != path:
        raise RuntimeError(f"unexpected certificate directory {rel}")
    return path


def drop_legacy_openshell(stage):
    """Drop retired runtime files only from this newly assembled staging tree."""
    for rel in ["opt/openshell", "etc/yoloctl/sandbox-policy.rego"]:
        leaf = stage / rel
        parent_rel = str(Path(rel).parent)
        if not leaf.parent.exists() and not leaf.parent.is_symlink():
            continue
        if guest_path(stage, "/" + parent_rel) != leaf.parent:
            raise RuntimeError(f"redirected retired runtime parent {parent_rel}")
        if leaf.is_symlink() or leaf.is_file():
            leaf.unlink()
        elif leaf.is_dir():
            shutil.rmtree(leaf)
        elif leaf.exists():
            raise RuntimeError(f"unexpected retired runtime file type {rel}")


def drop_managed_certificates(stage):
    """Remove the base Mozilla set and generated store before package extraction."""
    if (stage / MOZILLA_CERTS).exists() or (stage / MOZILLA_CERTS).is_symlink():
        shutil.rmtree(staged_directory(stage, MOZILLA_CERTS))
    if (stage / LOCAL_CERTS).exists() or (stage / LOCAL_CERTS).is_symlink():
        for entry in staged_directory(stage, LOCAL_CERTS).iterdir():
            raise RuntimeError(f"base image has a local CA certificate {entry.name}")
    if not ((stage / ETC_CERTS).exists() or (stage / ETC_CERTS).is_symlink()):
        return
    for entry in sorted(staged_directory(stage, ETC_CERTS).iterdir()):
        if entry.is_symlink():
            managed = os.readlink(entry).startswith("/" + CA_DIR + "/") or HASH_LINK.fullmatch(entry.name)
        else:
            managed = entry.name == "ca-certificates.crt" and entry.is_file()
        if not managed:
            raise RuntimeError(f"base image has an unmanaged certificate store entry {entry.name}")
        entry.unlink()


def pem_certificate(data, name):
    blocks = re.findall(rb"-----BEGIN ([^-\n]+)-----\r?\n(.*?)-----END \1-----", data, re.S)
    if len(blocks) != 1 or blocks[0][0] != b"CERTIFICATE" or data.count(b"-----BEGIN") != 1:
        raise RuntimeError(f"{name} does not contain exactly one PEM certificate")
    return base64.b64decode(b"".join(blocks[0][1].split()), validate=True)


def replace_staged_file(stage, rel, data):
    path = stage / rel
    if guest_path(stage, "/" + str(Path(rel).parent)) != path.parent:
        raise RuntimeError(f"unexpected certificate store parent {rel}")
    if path.is_symlink() or path.exists():
        path.unlink()
    with path.open("xb") as stream:
        stream.write(data)
    path.chmod(0o644)


def rebuild_trust_store(stage):
    """Regenerate update-ca-certificates and `openssl rehash` output."""
    root = staged_directory(stage, CA_DIR)
    certs = sorted((str(p.relative_to(root)) for p in root.rglob("*.crt") if p.is_file() and not p.is_symlink()), key=os.fsencode)
    if not certs:
        raise RuntimeError("pinned CA package provided no certificates")
    directory = staged_directory(stage, ETC_CERTS)
    for entry in directory.iterdir():
        raise RuntimeError(f"unexpected certificate store entry {entry.name} before regeneration")
    conf, bundle, links = [CERTS_CONF_HEADER], bytearray(), []
    for cert in certs:
        source = root / cert
        data = source.read_bytes()
        fingerprint = hashlib.sha256(pem_certificate(data, cert)).hexdigest()
        if fingerprint in DISTRUSTED_ROOTS:
            raise RuntimeError(f"pinned CA package still trusts {DISTRUSTED_ROOTS[fingerprint]} ({cert})")
        subject_hash = inputs.run(["openssl", "x509", "-noout", "-subject_hash", "-in", source], capture_output=True, text=True).stdout.strip()
        if not re.fullmatch(r"[0-9a-f]{8}", subject_hash):
            raise RuntimeError(f"{cert}: invalid subject hash")
        name = Path(cert).name.removesuffix(".crt").replace(" ", "_").replace("(", "=").replace(")", "=").replace(",", "_") + ".pem"
        link = directory / name
        if link.is_symlink() or link.exists():
            raise RuntimeError(f"duplicate certificate link {name}")
        link.symlink_to("/" + CA_DIR + "/" + cert)
        links.append((name, subject_hash, fingerprint))
        conf.append(cert + "\n")
        bundle += data
        if data and not data.endswith(b"\n"):
            bundle += b"\n"
    # `openssl rehash` visits names in strcmp order, skips repeated
    # certificates and numbers equal subject hashes from zero.
    seen, numbers = set(), {}
    for name, subject_hash, fingerprint in sorted(links, key=lambda link: os.fsencode(link[0])):
        if fingerprint in seen:
            continue
        seen.add(fingerprint)
        number = numbers.get(subject_hash, 0)
        numbers[subject_hash] = number + 1
        (directory / f"{subject_hash}.{number}").symlink_to(name)
    replace_staged_file(stage, CERTS_CONF, "".join(conf).encode())
    replace_staged_file(stage, CERTS_BUNDLE, bytes(bundle))


def verify_runtime(stage):
    required = ["/usr/sbin/sshd", "/usr/bin/ssh", "/usr/bin/sshfs", "/usr/bin/sudo", "/usr/bin/socat",
                "/usr/sbin/ip", "/usr/sbin/iptables", "/usr/sbin/ip6tables", "/usr/sbin/iptables-save",
                "/usr/sbin/nft", "/usr/bin/python3", "/usr/bin/findmnt", "/usr/bin/nsenter",
                "/usr/bin/setsid", "/usr/bin/flock", "/usr/bin/curl", "/usr/sbin/blkid", "/usr/sbin/fstrim", "/bin/bash"]
    seen = set()
    search = ["/lib/x86_64-linux-gnu", "/usr/lib/x86_64-linux-gnu", "/lib64", "/lib", "/usr/libexec/sudo"]
    while required:
        name = required.pop()
        path = guest_path(stage, name)
        if path in seen:
            continue
        seen.add(path)
        if not path.is_file():
            raise RuntimeError(f"required guest dependency is missing: {name}")
        if path.read_bytes()[:4] != b"\x7fELF":
            continue
        dynamic = inputs.run(["readelf", "-d", path], capture_output=True, text=True).stdout
        program = inputs.run(["readelf", "-l", path], capture_output=True, text=True).stdout
        required.extend(re.findall(r"Requesting program interpreter: ([^\]]+)", program))
        for lib in re.findall(r"Shared library: \[([^\]]+)\]", dynamic):
            found = next((directory + "/" + lib for directory in search if guest_path(stage, directory + "/" + lib).is_file()), None)
            if not found:
                raise RuntimeError(f"missing {lib} required by {name}")
            required.append(found)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True)
    parser.add_argument("--kernel-build", required=True)
    parser.add_argument("--cache")
    parser.add_argument("--unsquashfs", default="unsquashfs")
    parser.add_argument("--init-binary", required=True)
    parser.add_argument("--init-sha256", required=True)
    parser.add_argument("--guest-protocol", type=int, required=True)
    args = parser.parse_args()
    build(args)


if __name__ == "__main__":
    main()
