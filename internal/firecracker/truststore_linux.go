// The pinned ca-certificates package replaces the base image's Mozilla set.
// Package maintainer scripts never run during assembly, so the generated store
// is rebuilt as a fresh installation would leave it: update-ca-certificates
// with a newly generated configuration, followed by `openssl rehash`.
const (
	caCertificatesDir = "usr/share/ca-certificates"
	mozillaCertsDir   = caCertificatesDir + "/mozilla"
	localCertsDir     = "usr/local/share/ca-certificates"
	etcCertsDir       = "etc/ssl/certs"
	certsBundle       = etcCertsDir + "/ca-certificates.crt"
	certsConf         = "etc/ca-certificates.conf"
)

// The header ca-certificates' postinst writes for a new configuration.
const certsConfHeader = `# This file lists certificates that you wish to use or to ignore to be
# installed in /etc/ssl/certs.
# update-ca-certificates(8) will update /etc/ssl/certs by reading this file.
#
# This is autogenerated by dpkg-reconfigure ca-certificates.
# Certificates should be installed under /usr/share/ca-certificates
# and files with extension '.crt' is recognized as available certs.
#
# line begins with # is comment.
# line begins with ! is certificate filename to be deselected.
#
`

// SHA-256 fingerprints of roots that must not return through a stale input:
// Ubuntu's LP: #2171507 fix distrusts emSign ECC Root CA - G3, and Mozilla
// had already removed AAA Certificate Services, which the base image ships.
var distrustedRoots = map[string]string{
	"86a1ecba089c4a8d3bbe2734c612ba341d813e043cf9e8a862cd5c57a36bbe6b": "emSign ECC Root CA - G3",
	"d7a7a0fb5d7e2731d771e9484ebcdef71d5f0c3e0a2948782bc83ee0ea699ef4": "AAA Certificate Services",
}

var hashLinkName = regexp.MustCompile(`^[0-9a-f]{8}\.r?[0-9]+$`)

// dropManagedCertificates removes the base image's Mozilla certificates and
// generated store before package extraction, so certificates the pinned package
// no longer ships cannot survive as files, links or bundle entries. Content that
// a fresh package installation would not regenerate is refused.
func (t imageTree) dropManagedCertificates() error {
	for name, e := range t {
		switch {
		case strings.HasPrefix(name, mozillaCertsDir+"/"):
			delete(t, name)
		case strings.HasPrefix(name, localCertsDir+"/"):
			return fmt.Errorf("base image has a local CA certificate %s", name)
		case path.Dir(name) == etcCertsDir:
			base := path.Base(name)
			switch {
			case name == certsBundle && e.header.Typeflag == tar.TypeReg:
			case e.header.Typeflag == tar.TypeSymlink && strings.HasPrefix(e.header.Linkname, "/"+caCertificatesDir+"/"):
			case e.header.Typeflag == tar.TypeSymlink && hashLinkName.MatchString(base):
			default:
				return fmt.Errorf("base image has an unmanaged certificate store entry %s", name)
			}
			delete(t, name)
		case strings.HasPrefix(name, etcCertsDir+"/"):
			return fmt.Errorf("base image has an unmanaged certificate store entry %s", name)
		}
	}
	return nil
}

// rebuildTrustStore regenerates the configuration, per-certificate links,
// bundle and subject-hash links from the extracted package certificates.
func (t imageTree) rebuildTrustStore() error {
	var certs []string
	for name, e := range t {
		if strings.HasPrefix(name, etcCertsDir+"/") {
			return fmt.Errorf("unexpected certificate store entry %s before regeneration", name)
		}
		if strings.HasPrefix(name, caCertificatesDir+"/") && strings.HasSuffix(name, ".crt") && e.header.Typeflag == tar.TypeReg {
			certs = append(certs, strings.TrimPrefix(name, caCertificatesDir+"/"))
		}
	}
	if len(certs) == 0 {
		return errors.New("pinned CA package provided no certificates")
	}
	if e, ok := t[etcCertsDir]; !ok || e.header.Typeflag != tar.TypeDir {
		return fmt.Errorf("%s is not a directory", etcCertsDir)
	}
	// update-ca-certificates follows the configuration order, which the
	// package writes sorted in the C locale.
	slices.Sort(certs)
	conf := []byte(certsConfHeader)
	var bundle []byte
	type stored struct {
		pem  string
		hash uint32
		der  [sha256.Size]byte
	}
	var links []stored
	for _, cert := range certs {
		data, err := t.readRegular(caCertificatesDir + "/" + cert)
		if err != nil {
			return err
		}
		block, rest := pem.Decode(data)
		if block == nil || block.Type != "CERTIFICATE" || bytes.Contains(rest, []byte("-----BEGIN")) {
			return fmt.Errorf("%s does not contain exactly one PEM certificate", cert)
		}
		fingerprint := sha256.Sum256(block.Bytes)
		if root, ok := distrustedRoots[hex.EncodeToString(fingerprint[:])]; ok {
			return fmt.Errorf("pinned CA package still trusts %s (%s)", root, cert)
		}
		subject, err := certificateSubject(block.Bytes)
		if err != nil {
			return fmt.Errorf("%s: %w", cert, err)
		}
		hash, err := opensslSubjectHash(subject)
		if err != nil {
			return fmt.Errorf("%s: %w", cert, err)
		}
		pemName := strings.NewReplacer(" ", "_", "(", "=", ")", "=", ",", "_").Replace(strings.TrimSuffix(path.Base(cert), ".crt")) + ".pem"
		if _, ok := t[etcCertsDir+"/"+pemName]; ok {
			return fmt.Errorf("duplicate certificate link %s", pemName)
		}
		t.link(etcCertsDir+"/"+pemName, "/"+caCertificatesDir+"/"+cert)
		links = append(links, stored{pemName, hash, fingerprint})
		conf = append(append(conf, cert...), '\n')
		bundle = append(bundle, data...)
		if len(data) > 0 && data[len(data)-1] != '\n' {
			bundle = append(bundle, '\n')
		}
	}
	// `openssl rehash` visits names in strcmp order, skips repeated
	// certificates and numbers equal subject hashes from zero.
	slices.SortFunc(links, func(a, b stored) int { return strings.Compare(a.pem, b.pem) })
	seen := map[[sha256.Size]byte]bool{}
	next := map[uint32]int{}
	for _, l := range links {
		if seen[l.der] {
			continue
		}
		seen[l.der] = true
		t.link(fmt.Sprintf("%s/%08x.%d", etcCertsDir, l.hash, next[l.hash]), l.pem)
		next[l.hash]++
	}
	t.put(certsConf, 0644, conf)
	t.put(certsBundle, 0644, bundle)
	return nil
}

func (t imageTree) readRegular(name string) ([]byte, error) {
	e, ok := t[name]
	if !ok || e.header.Typeflag != tar.TypeReg || e.open == nil || e.header.Size > 1<<20 {
		return nil, fmt.Errorf("invalid certificate file %s", name)
	}
	r, err := e.open()
	if err != nil {
		return nil, err
	}
	data, err := io.ReadAll(io.LimitReader(r, (1<<20)+1))
	err = errors.Join(err, r.Close())
	if err == nil && int64(len(data)) != e.header.Size {
		err = fmt.Errorf("certificate file %s changed size", name)
	}
	return data, err
}

// certificateSubject returns the encoded subject Name of a DER certificate
// without applying x509 parser policy to the root itself.
func certificateSubject(der []byte) ([]byte, error) {
	var cert, tbs, field asn1.RawValue
	if rest, err := asn1.Unmarshal(der, &cert); err != nil || len(rest) != 0 || cert.Tag != asn1.TagSequence {
		return nil, errors.New("invalid certificate encoding")
	}
	if _, err := asn1.Unmarshal(cert.Bytes, &tbs); err != nil || tbs.Tag != asn1.TagSequence {
		return nil, errors.New("invalid certificate body")
	}
	rest := tbs.Bytes
	next := func() (err error) {
		rest, err = asn1.Unmarshal(rest, &field)
		return err
	}
	// An optional version [0] precedes serial, signature, issuer, validity
	// and subject.
	if err := next(); err != nil {
		return nil, errors.New("invalid certificate fields")
	}
	skip := 4
	if field.Class == asn1.ClassContextSpecific && field.Tag == 0 {
		skip = 5
	}
	for range skip {
		if err := next(); err != nil {
			return nil, errors.New("invalid certificate fields")
		}
	}
	if field.Class != asn1.ClassUniversal || field.Tag != asn1.TagSequence {
		return nil, errors.New("invalid certificate subject")
	}
	return field.FullBytes, nil
}

// opensslSubjectHash implements OpenSSL's X509_NAME_hash: the first four bytes
// of SHA-1 over the canonical name encoding, as a little-endian integer. The
// canonical form converts string values to UTF-8, trims and collapses ASCII
// whitespace, lowercases ASCII letters and omits the outer SEQUENCE.
func opensslSubjectHash(subject []byte) (uint32, error) {
	var rdns []asn1.RawValue
	if rest, err := asn1.Unmarshal(subject, &rdns); err != nil || len(rest) != 0 {
		return 0, errors.New("invalid subject name")
	}
	var canonical []byte
	for _, rdn := range rdns {
		if rdn.Class != asn1.ClassUniversal || rdn.Tag != asn1.TagSet || !rdn.IsCompound {
			return 0, errors.New("invalid relative distinguished name")
		}
		var entries [][]byte
		for rest := rdn.Bytes; len(rest) > 0; {
			var atv struct{ Type, Value asn1.RawValue }
			var err error
			if rest, err = asn1.Unmarshal(rest, &atv); err != nil || atv.Type.Tag != asn1.TagOID {
				return 0, errors.New("invalid name attribute")
			}
			value, err := canonicalNameValue(atv.Value)
			if err != nil {
				return 0, err
			}
			entries = append(entries, derElement(0x30, append(slices.Clone(atv.Type.FullBytes), value...)))
		}
		// DER SET OF: elements sorted by their encodings.
		slices.SortFunc(entries, bytes.Compare)
		canonical = append(canonical, derElement(0x31, bytes.Join(entries, nil))...)
	}
	sum := sha1.Sum(canonical)
	return binary.LittleEndian.Uint32(sum[:4]), nil
}

func canonicalNameValue(v asn1.RawValue) ([]byte, error) {
	if v.Class != asn1.ClassUniversal || v.IsCompound {
		return v.FullBytes, nil
	}
	var text []byte
	switch v.Tag {
	case asn1.TagUTF8String:
		if !utf8.Valid(v.Bytes) {
			return nil, errors.New("invalid UTF-8 name value")
		}
		text = v.Bytes
	case asn1.TagPrintableString, asn1.TagT61String, asn1.TagIA5String, 26: // VisibleString
		for _, b := range v.Bytes {
			text = utf8.AppendRune(text, rune(b))
		}
	case asn1.TagBMPString, 28: // UniversalString
		width := 2
		if v.Tag == 28 {
			width = 4
		}
		if len(v.Bytes)%width != 0 {
			return nil, errors.New("invalid wide name value")
		}
		for i := 0; i < len(v.Bytes); i += width {
			var r uint32
			for _, b := range v.Bytes[i : i+width] {
				r = r<<8 | uint32(b)
			}
			// OpenSSL 3 refuses surrogates and values beyond Unicode.
			if r > utf8.MaxRune || !utf8.ValidRune(rune(r)) {
				return nil, errors.New("invalid wide name value")
			}
			text = utf8.AppendRune(text, rune(r))
		}
	default:
		return v.FullBytes, nil
	}
	space := func(b byte) bool { return b == ' ' || (b >= '\t' && b <= '\r') }
	for len(text) > 0 && space(text[0]) {
		text = text[1:]
	}
	for len(text) > 0 && space(text[len(text)-1]) {
		text = text[:len(text)-1]
	}
	out := make([]byte, 0, len(text))
	for i := 0; i < len(text); i++ {
		switch b := text[i]; {
		case space(b):
			out = append(out, ' ')
			for i+1 < len(text) && space(text[i+1]) {
				i++
			}
		case b >= 'A' && b <= 'Z':
			out = append(out, b+'a'-'A')
		default:
			out = append(out, b)
		}
	}
	return derElement(asn1.TagUTF8String, out), nil
}

func derElement(tag byte, content []byte) []byte {
	out := []byte{tag}
	if n := len(content); n < 0x80 {
		out = append(out, byte(n))
	} else {
		var length []byte
		for ; n > 0; n >>= 8 {
			length = append([]byte{byte(n)}, length...)
		}
		out = append(append(out, 0x80|byte(len(length))), length...)
	}
	return append(out, content...)
}
