// A real PTY peer sets its own modes and records every input byte. The final
// sentinel shares the ordered input queue, so absence of extra bytes is tested
// without relying on sleeps or on the expected input's length.
const compatibilityPeer = `import os,sys,tty
tty.setraw(0)
os.write(1,sys.argv[2].encode()+b'COMPAT_READY')
data=b''
end=b'\x00YOLOCTL_COMPAT_END\x00'
while not data.endswith(end):
 data+=os.read(0,65536)
open(sys.argv[1],'wb').write(data[:-len(end)])
`

func compatibilityCapture(t *testing.T, m *model, modes string) (*term.Session, func() string) {
	t.Helper()
	path := t.TempDir() + "/input"
	s, err := term.Start(term.Options{Rows: m.viewRows(), Cols: m.width, Argv: []string{
		"python3", "-c", compatibilityPeer, path, modes}})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(s.Close)
	deadline := time.Now().Add(5 * time.Second)
	for !strings.Contains(s.GridText(), "COMPAT_READY") && time.Now().Before(deadline) {
		time.Sleep(time.Millisecond)
	}
	if !strings.Contains(s.GridText(), "COMPAT_READY") {
		t.Fatal("compatibility peer did not become ready")
	}
	m.tabs.Add(testTab(s, "compatibility-test", false))
	m.focusPalette = false
	return s, func() string {
		t.Helper()
		if err := s.SendInput([]byte("\x00YOLOCTL_COMPAT_END\x00")); err != nil {
			t.Fatal(err)
		}
		if err := s.Wait(5 * time.Second); err != nil {
			t.Fatal(err)
		}
		p, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		return string(p)
	}
}

func runCompatibilityInput(t *testing.T, m *model, input string, fragmented bool) {
	t.Helper()
	var reader io.Reader = strings.NewReader(input + "\x1b[24~") // F12 ends only the harness.
	if fragmented {
		reader = bytewiseReader{reader}
	}
	ctx, cancel := context.WithTimeout(t.Context(), 5*time.Second)
	defer cancel()
	p := tea.NewProgram(paletteKeyboardModel{m}, tea.WithContext(ctx),
		tea.WithInput(reader), tea.WithOutput(io.Discard), tea.WithWindowSize(m.width, m.height),
		tea.WithEnvironment([]string{"TERM=xterm-256color"}), tea.WithoutSignals())
	if _, err := p.Run(); err != nil {
		t.Fatal(err)
	}
}

// Literal wire expectations cover the real host reader, model, child encoder,
// ordered queue and PTY. They are not generated by the implementation. Kitty
// key 0 with associated text is a text-only/IME event, not Ctrl+Space:
// https://sw.kovidgoyal.net/kitty/keyboard-protocol/#text-as-code-points
// The scripted host intentionally never answers geometry or mouse queries.
// This verifies fallback without claiming a graphical IME or terminal was run.
func TestHostCompatibilityInputThroughPTY(t *testing.T) {
	const text = "é e\u0301 界 日本語 👩\u200d💻 🇯🇵 क्\u200dष"
	for _, tc := range []struct {
		name, modes, input, want string
		kitty                    bool
	}{
		{"legacy UTF-8", "", text, text, false},
		{"legacy controls", "", "\r\t\x7f\n\x00\x01\x1b[A\x1b[1;5D\x1bé", "\r\t\x7f\n\x00\x01\x1b[A\x1b[1;5D\x1bé", false},
		{"legacy application cursor", "\x1b[?1h", "\x1b[A\x1b[D", "\x1bOA\x1bOD", false},
		{"legacy host enhanced child", "\x1b[>3u", "\r\t\x7f\n\x03\x1b[A", "\r\t\x7f\x1b[106;5u\x1b[99;5u\x1b[1A", false},
		{"unbracketed paste", "", "\x1b[200~日本語\n🙂\x1b[201~", "日本語\n🙂", false},
		{"bracketed paste", "\x1b[?2004h", "\x1b[200~日本語\n🙂\x1b[201~", "\x1b[200~日本語\n🙂\x1b[201~", false},
		{"IME legacy child", "", "\x1b[0;;26085:26412:35486u", "日本語", true},
		{"IME disambiguated child", "\x1b[>3u", "\x1b[0;;26085:26412:35486u", "日本語", true},
		{"IME without associated text", "\x1b[>9u", "\x1b[0;;26085:26412:35486u", "日本語", true},
		{"IME associated text child", "\x1b[>31u", "\x1b[0;;26085:26412:35486u", "\x1b[0;1;26085:26412:35486u", true},
		{"IME release cannot insert text", "\x1b[>31u", "\x1b[0;;26085:26412:35486u\x1b[0;1:3;26085:26412:35486u", "\x1b[0;1;26085:26412:35486u", true},
		{"composed key legacy child", "", "\x1b[101;1;101:769u", "e\u0301", true},
		{"composed key associated text child", "\x1b[>31u", "\x1b[101;1;101:769u\x1b[101;1:3u", "\x1b[101;1;101:769u\x1b[101;1:3u", true},
		{"enhanced Control-Space", "", "\x1b[32;5u\x1b[0u", "\x00\x00", true},
	} {
		for _, fragmented := range []bool{false, true} {
			t.Run(fmt.Sprintf("%s/fragmented=%t", tc.name, fragmented), func(t *testing.T) {
				m := newTestModel(t, 80, 24)
				_, capture := compatibilityCapture(t, m, tc.modes)
				input := tc.input
				if tc.kitty {
					input = "\x1b[?0u" + input // Zero still means Kitty support.
				}
				runCompatibilityInput(t, m, input, fragmented)
				if got := capture(); got != tc.want {
					t.Fatalf("PTY received %q, want %q", got, tc.want)
				}
				if m.hostKitty != tc.kitty || m.hostGeometry.width != 0 || m.hostMouseEncoding.pixels {
					t.Fatal("unanswered host capabilities were assumed")
				}
			})
		}
	}
}

func TestHostCompatibilityPaletteText(t *testing.T) {
	for _, input := range []string{"日本語e\u0301", "\x1b[?0u\x1b[0;;26085:26412:35486u\x1b[101;1;101:769u"} {
		for _, fragmented := range []bool{false, true} {
			m := newTestModel(t, 80, 24)
			runCompatibilityInput(t, m, input, fragmented)
			if line, _ := m.pal.Line(); line != "日本語e\u0301" {
				t.Fatalf("input %q (fragmented %t): palette text = %q", input, fragmented, line)
			}
		}
	}
}

func TestHostCompatibilityFocusOwnership(t *testing.T) {
	m := newTestModel(t, 80, 24)
	_, first := compatibilityCapture(t, m, "\x1b[?1004h")
	_, second := compatibilityCapture(t, m, "\x1b[?1004h")
	_, unrequested := compatibilityCapture(t, m, "")
	m.activateTab(0)
	// Duplicate host reports are ignored. Palette navigation moves through
	// the second and third tab; only the actual focused, opted-in peer gets I.
	const switchTab = "\x19\x1b[1;5C\x1b[27u"
	runCompatibilityInput(t, m, "\x1b[I\x1b[I\x1b[O\x1b[O\x1b[I"+
		switchTab+"\x1b[O\x1b[I"+switchTab+"\x1b[O\x1b[I", true)
	if got := first(); got != "\x1b[I\x1b[O\x1b[I\x1b[O" {
		t.Fatalf("first tab focus = %q", got)
	}
	if got := second(); got != "\x1b[O\x1b[I\x1b[O\x1b[I\x1b[O" {
		t.Fatalf("second tab focus = %q", got)
	}
	if got := unrequested(); got != "" {
		t.Fatalf("unsolicited focus reached non-reporting peer: %q", got)
	}
}

// Explicit cell positions and DECSCUSR expectations exercise native output,
// chrome offsets and the host-facing View. Both width profiles agree for these
// characters; ZWJ/ambiguous-width policies on arbitrary hosts are not asserted.
func TestHostCompatibilityUnicodeCellsAndCursor(t *testing.T) {
	for _, standalone := range []bool{false, true} {
		m := newTestModel(t, 40, 12)
		m.standalone = standalone
		s := frameTestTab(t, m)
		_, _ = s.Write([]byte("\x1b[2J\x1b[2;3HA界e\u0301🙂"))
		for style, want := range []struct {
			shape tea.CursorShape
			blink bool
		}{
			{tea.CursorBlock, true}, {tea.CursorBlock, true}, {tea.CursorBlock, false},
			{tea.CursorUnderline, true}, {tea.CursorUnderline, false},
			{tea.CursorBar, true}, {tea.CursorBar, false},
		} {
			_, _ = s.Write(fmt.Appendf(nil, "\x1b[%d q", style))
			v := m.View()
			c := v.Cursor
			if c == nil || c.X != 8 || c.Y != 1+m.chromeRows() || c.Shape != want.shape || c.Blink != want.blink {
				t.Fatalf("standalone=%t style=%d: host cursor=%+v", standalone, style, c)
			}
			for _, method := range []ansi.Method{ansi.WcWidth, ansi.GraphemeWidth} {
				buf := uv.NewScreenBuffer(40, 12)
				buf.Method = method
				uv.NewStyledString(v.Content).Draw(buf, buf.Bounds())
				for x, text := range map[int]string{2: "A", 3: "界", 5: "e\u0301", 6: "🙂"} {
					if cell := buf.CellAt(x, c.Y); cell.Content != text {
						t.Fatalf("method=%d cell (%d,%d)=%+v, want %q", method, x, c.Y, cell, text)
					}
				}
			}
		}
		_, _ = s.Write([]byte("\x1b[?25l"))
		if m.View().Cursor != nil {
			t.Fatal("hidden application cursor remained visible")
		}
		_, _ = s.Write([]byte("\x1b[?25h"))
		if m.View().Cursor == nil {
			t.Fatal("restored application cursor remained hidden")
		}
		m.tabs.Focused().Exited = true
		if m.View().Cursor != nil {
			t.Fatal("exited surface kept an input cursor")
		}
	}
}
